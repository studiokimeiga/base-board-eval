#!/usr/bin/env python3
"""Read the owner's probe answers and say which way each decision in PROBE.md goes.

  python calibration/probe/analyze_probe.py [EXPORT.json]

With no argument it reads the latest export (by its `exported` time) in calibration/probe/answers/.
Writes calibration/probe/RESULTS.md and prints it. Uses only key-probe.json and the export: no
thread text.
"""
import glob, json, os, sys
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))

# decision -> (question, {source: what winning means}); fixed in PROBE.md before any answer
DECISIONS = {
    "engine": ("Small local base-model cast or hosted Gemini (neutral header)?",
               {"smallcast": "build the English board on the small local cast (GPU, XTC + DRY, a picker for coherence)",
                "gemini-neutral": "build the English board on hosted Gemini under a neutral header"}),
    "qwen": ("Qwen3-235B raw continuation or Gemini, same /x/ header?",
             {"qwen-raw": "a raw-continuation round (Qwen + picker, neutral header) is worth running",
              "gemini-x": "drop raw continuation"}),
    "register": ("Paranormal /x/ label or a neutral board?",
                 {"gemini-x": "keep a paranormal board identity", "roles-x": "keep a paranormal board identity",
                  "gemini-neutral": "a general board, strange things as contrast",
                  "roles-neutral": "a general board, strange things as contrast"}),
    "roles": ("Poster temperaments or plain Gemini, neutral header?",
              {"roles-neutral": "keep temperaments", "gemini-neutral": "drop temperaments (simpler)"}),
    "naif": ("An occasional small-model poster among Gemini posters?",
             {"roles-x-naif": "keep the confused poster; next test seeding a shared confusion",
              "roles-x": "drop the small-model poster"}),
    "chaos": ("Small cast: recommended sampler (t0.5 + DRY) or hotter, no DRY?",
              {"small-t05": "keep the recommended sampler", "small-t15-nodry": "loosen the sampler: more chaos is fine"}),
    "jp-engine": ("Japanese: Gemini or Qwen raw?", {"jp-gemini": "Gemini for the Japanese board", "jp-qwen": "Qwen raw for the Japanese board"}),
    "jp-tidy": ("Japanese: 5ch-natural Gemini or tidier GPT-5.4?",
                {"jp-gemini": "keep the natural 5ch register", "jp-gpt": "favour a tidier, more learnable register"}),
    "jp-format": ("Japanese: anonymous 5ch IDs or named handles?",
                  {"jp-gemini": "anonymous 5ch format", "jp-gemini-named": "named handles"}),
}


def latest(folder):
    best = None
    for path in glob.glob(os.path.join(folder, "*.json")):
        with open(path, encoding="utf-8") as f:
            d = json.load(f)
        if best is None or d.get("exported", "") > best[1].get("exported", ""):
            best = (path, d)
    return best


def verdict(wins, both, neither, n):
    """A side wins a decision when it takes every decided pair, or all but one of three or more."""
    decided = sum(wins.values())
    if not n:
        return "not answered"
    if not decided:
        return "no preference (both good %d, neither %d)" % (both, neither)
    top, k = wins.most_common(1)[0]
    if k == decided:
        return "**%s**" % top
    if decided >= 3 and k >= decided - 1:
        return "**%s** (mostly)" % top
    return "split"


def main():
    with open(os.path.join(HERE, "key-probe.json"), encoding="utf-8") as f:
        key = json.load(f)
    if len(sys.argv) > 1:
        path = sys.argv[1]
        with open(path, encoding="utf-8") as f:
            export = json.load(f)
    else:
        found = latest(os.path.join(HERE, "answers"))
        if not found:
            raise SystemExit("no export in calibration/probe/answers/")
        path, export = found
    answers = export.get("answers", {})
    lines = ["# Taste probe results", "",
             "Generated by `analyze_probe.py` from `%s` (exported %s). The decisions and what each outcome "
             "means are fixed in PROBE.md." % (os.path.basename(path), export.get("exported", "?")), "",
             "| decision | pairs answered | picks (what each choice means) | verdict |", "|---|---:|---|---|"]
    tags = Counter()
    detail = []
    for dec, (question, means) in DECISIONS.items():
        pids = [p for p in sorted(key) if key[p]["decision"] == dec]
        wins, both, neither, n = Counter(), 0, 0, 0
        for p in pids:
            a = answers.get(p) or {}
            pick = a.get("pick")
            for side in "AB":
                for t in (a.get("tags") or {}).get(side, []):
                    tags[(key[p][side]["source"], t)] += 1
            if not pick:
                continue
            n += 1
            if pick in "AB":            # sources that mean the same choice (/x/ Gemini, /x/ roles) count together
                wins[means[key[p][pick]["source"]]] += 1
            elif pick == "both":
                both += 1
            else:
                neither += 1
            stars = {s: (a.get("stars") or {}).get(s, []) for s in "AB"}
            detail.append("- %s (%s): %s%s%s%s" % (
                p, dec, key[p][pick]["source"] if pick in "AB" else pick,
                "; stars " + ", ".join("%s #%s" % (key[p][s]["source"], ",".join(map(str, sorted(v))))
                                       for s, v in stars.items() if v) if any(stars.values()) else "",
                "; seen before" if a.get("seen") else "",
                "; note: " + a["note"] if a.get("note") else ""))
        v = verdict(wins, both, neither, n)
        picks = ", ".join("%d for %s" % (c, m) for m, c in wins.most_common())
        extra = ", ".join(x for x in ("%d both good" % both if both else "", "%d neither" % neither if neither else "") if x)
        lines.append("| %s | %d of %d | %s | %s |" % (
            question, n, len(pids), "; ".join(x for x in (picks, extra) if x) or "–",
            "**decided**" if v.startswith("**") and "mostly" not in v else
            "**mostly decided**" if "mostly" in v else v))
    lines += ["", "## Pair by pair", ""] + (detail or ["No pair answered yet."])
    lines += ["", "## Tags by source", "", "| source | tag | times |", "|---|---|---:|"]
    lines += ["| %s | %s | %d |" % (s, t, c) for (s, t), c in sorted(tags.items())] or []
    lines += ["", "One pair per thread pair: with two or three pairs a decision, a verdict is a direction to "
              "test next, not a measurement. The blind calibration sets stay the measurement."]
    text = "\n".join(lines) + "\n"
    with open(os.path.join(HERE, "RESULTS.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    sys.stdout.buffer.write(text.encode("utf-8"))


if __name__ == "__main__":
    main()
